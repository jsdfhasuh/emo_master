def buildContract(output, *, wheel=True, regenerateProto=True):
    output = Path(output).resolve()
    if regenerateProto:
        subprocess.run([sys.executable, str(ROOT / 'scripts/gen_proto.py')], cwd=ROOT, check=True)
    output.mkdir(parents=True, exist_ok=True)
    schemas = {name: {'$schema': JSON_SCHEMA, **model.model_json_schema()} for name, model in MODELS.items()}
    schemas['runtime-rpc'] = protobufSchema()
    for name, schema in schemas.items():
        writeJson(output / 'schemas' / (name + '.schema.json'), schema)
    (output / 'typescript').mkdir(exist_ok=True)
    (output / 'typescript' / 'panel-contract.ts').write_text(generateTypes(schemas), encoding='utf-8')
    (output / 'proto').mkdir(exist_ok=True)
    shutil.copyfile(ROOT / 'proto/runtime.proto', output / 'proto/runtime.proto')
    shutil.copyfile(ROOT / 'docs/development/panel-contract-v1.md', output / 'README.md')
    sampleRoot = output / 'sample-panels' / 'source'
    sampleRoot.mkdir(parents=True, exist_ok=True)
    # Save through the real project API in a fresh workspace, so repeated builds
    # do not turn the previous generated sample into a delivered .bak file.
    with tempfile.TemporaryDirectory(prefix='emo-panel-sample-') as directory:
        sample = Path(directory)
        document, manifest = sampleProject(sample)
        for name in ('demo.emoproj', 'demo.png'):
            shutil.copyfile(sample / name, sampleRoot / name)
        shutil.copyfile(sample / 'demo.emoweb', output / 'sample-panels' / 'demo.emoweb')
    fixtureIndex = {}
    for name, (schema, value) in fixtureValues(manifest).items():
        # JSON mode accepts the same tuple/union representation transported to browsers.
        checked = MODELS[schema].model_validate_json(json.dumps(value)).model_dump(mode='json', exclude_none=True)
        writeJson(output / 'fixtures' / (name + '.json'), checked)
        fixtureIndex[name + '.json'] = {'schema': '../schemas/' + schema + '.schema.json', 'synthetic': True}
    from google.protobuf.json_format import MessageToDict
    from emo_master.apps.runtime.grpc_server.generated import runtime_pb2 as pb
    for status in ('AVAILABLE', 'EMPTY', 'MISSING', 'UNSUPPORTED'):
        image = pb.HistoryImageReply(ok=True, status=status)
        if status == 'AVAILABLE':
            image.data = (sampleRoot / 'demo.png').read_bytes()
            image.mime_type, image.width, image.height = 'image/png', 48, 32
        filename = 'history-image-' + status.lower() + '.json'
        writeJson(output / 'fixtures' / filename, MessageToDict(image))
        fixtureIndex[filename] = {'schema': '../schemas/runtime-rpc.schema.json#/$defs/RpcHistoryImageReply', 'synthetic': True}
    vectors = []
    for value in ({'z': 1, 'a': '页面', 'emoji': '😀'}, {'float': 1.0, 'negativeZero': -0.0, 'small': 1e-7},
                  {'a': [True, None, {'b': 2}], 'largeInteger': 9007199254740993}, manifest['captureRequirements']):
        vectors.append(dict(input=value, canonicalUtf8=canonicalJson(value), sha256=revisionOf(value)))
    writeJson(output / 'fixtures/canonical-vectors.json', vectors)
    writeJson(output / 'fixtures/index.json', fixtureIndex)
    wheelFiles = []
    if wheel:
        destination = output / 'python'
        destination.mkdir(exist_ok=True)
        with tempfile.TemporaryDirectory(prefix='emo-panel-wheel-') as directory:
            subprocess.run([sys.executable, '-m', 'pip', 'wheel', str(ROOT / 'packages/emo_panel_protocol'),
                '--no-deps', '--no-build-isolation', '--wheel-dir', directory], cwd=ROOT, check=True)
            for artifact in Path(directory).glob('*.whl'):
                with zipfile.ZipFile(artifact) as archive:
                    names = set(archive.namelist())
                    required = {'emo_panel_protocol/generated/runtime_pb2.py',
                                'emo_panel_protocol/generated/runtime_pb2_grpc.py',
                                'emo_panel_protocol/messages.py', 'emo_panel_protocol/published.py',
                                'emo_panel_protocol/preview.py'}
                    if not required <= names or any(name.startswith('emo_master/') for name in names):
                        raise ValueError('SDK wheel is incomplete or contains the application package')
                shutil.copyfile(artifact, destination / artifact.name)
                wheelFiles.append('python/' + artifact.name)
        if not wheelFiles:
            raise ValueError('SDK wheel build returned no artifact')
    sha = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    dirty = bool(subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True).strip())
    files = {path.relative_to(output).as_posix(): dict(sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
             byteSize=path.stat().st_size) for path in sorted(output.rglob('*'))
             if path.is_file() and path != output / 'contract-manifest.json'}
    contract = dict(panelContractVersion='1.0', sdkVersion=__version__, sourceSha=sha, sourceDirty=dirty,
        projectSchemaVersion=document.schemaVersion, presentationSchemaVersion=document.presentation.schemaVersion,
        status='complete' if wheel else 'development-without-wheel', sdkWheels=wheelFiles,
        sampleValidation=dict(model='PASS', saveReload='PASS', workflowCompile='PASS',
            normalCapture='PASS', designerOpen='NOT_RUN'), files=files)
    writeJson(output / 'contract-manifest.json', contract)
    return contract


def archiveContract(output, destination):
    """Archive exactly the generated manifest and its verified delivery files."""
    output, destination = Path(output).resolve(), Path(destination).resolve()
    manifest = json.loads((output / 'contract-manifest.json').read_text(encoding='utf-8'))
    for name, expected in manifest['files'].items():
        data = (output / name).read_bytes()
        if expected != dict(sha256=hashlib.sha256(data).hexdigest(), byteSize=len(data)):
            raise ValueError('contract artifact changed before archiving: ' + name)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name in sorted(set(manifest['files']) | {'contract-manifest.json'}):
            archive.write(output / name, name)
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/panel-contract-v1')
    parser.add_argument('--no-wheel', action='store_true', help='development only; manifest marks missing wheel')
    parser.add_argument('--skip-proto', action='store_true', help='use already generated protobuf code')
    parser.add_argument('--archive', type=Path, help='write a complete ZIP from the generated manifest')
    options = parser.parse_args()
    result = buildContract(options.output, wheel=not options.no_wheel, regenerateProto=not options.skip_proto)
    if options.archive:
        archiveContract(options.output, options.archive)
    print(json.dumps(dict(output=str(options.output.resolve()), status=result['status'], files=len(result['files']))))


if __name__ == '__main__':
    main()
