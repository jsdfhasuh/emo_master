JSON_SCHEMA = 'https://json-schema.org/draft/2020-12/schema'


def writeJson(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n', encoding='utf-8')


def typeScript(schema):
    """Translate the generated schema's structural types; schema retains constraints."""
    if schema is True or schema == {}:
        return 'unknown'
    if schema is False:
        return 'never'
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(v, ensure_ascii=False) for v in schema['enum'])
    for keyword, operator in [('anyOf', ' | '), ('oneOf', ' | '), ('allOf', ' & ')]:
        if keyword in schema:
            return '(' + operator.join(typeScript(item) for item in schema[keyword]) + ')'
    kind = schema.get('type')
    if isinstance(kind, list):
        return '(' + ' | '.join(typeScript({**schema, 'type': item}) for item in kind) + ')'
    if kind == 'array':
        if 'prefixItems' in schema:
            return '[' + ', '.join(typeScript(item) for item in schema['prefixItems']) + ']'
        return 'Array<' + typeScript(schema.get('items', {})) + '>'
    if kind == 'object' or 'properties' in schema:
        required = set(schema.get('required', []))
        fields = [json.dumps(name) + ('' if name in required else '?') + ': ' + typeScript(item)
                  for name, item in schema.get('properties', {}).items()]
        additional = schema.get('additionalProperties', True)
        if additional is not False:
            fields.append('[key: string]: ' + typeScript(additional))
        return '{ ' + '; '.join(fields) + ' }'
    if kind in {'string', 'boolean', 'null'}:
        return kind
    if kind in {'integer', 'number'}:
        return 'number'
    raise ValueError('unhandled schema type: ' + repr(schema))


def generateTypes(schemas):
    definitions = {}
    for schema in schemas.values():
        for name, definition in schema.get('$defs', {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError('schema definition conflict: ' + name)
            definitions[name] = definition
        if 'title' in schema:
            definitions[schema['title']] = {k: v for k, v in schema.items() if k not in {'$defs', '$schema', '$id'}}
    return ('// Generated by scripts/build_panel_contract.py; do not edit.\n'
            '// JSON Schema owns range/pattern/semantic validation; these are structural types.\n\n' +
            '\n\n'.join('export type ' + name + ' = ' + typeScript(schema) + ';'
                         for name, schema in sorted(definitions.items())) + '\n')


def protobufSchema():
    """Derive protobuf JSON shapes from descriptors, preserving int64 and bytes rules."""
    from emo_master.apps.runtime.grpc_server.generated import runtime_pb2 as pb
    from google.protobuf.descriptor import FieldDescriptor as F
    definitions = {}

    def message(descriptor):
        name = 'Rpc' + descriptor.name
        if name in definitions:
            return {'$ref': '#/$defs/' + name}
        definitions[name] = {}
        properties = {}
        for field in descriptor.fields:
            if field.type == F.TYPE_MESSAGE:
                if field.message_type.GetOptions().map_entry:
                    item = {'type': 'object', 'additionalProperties': scalar(field.message_type.fields_by_name['value'])}
                else:
                    item = message(field.message_type)
            else:
                item = scalar(field)
            if field.is_repeated and not (field.type == F.TYPE_MESSAGE and field.message_type.GetOptions().map_entry):
                item = {'type': 'array', 'items': item}
            properties[field.json_name] = item
        definitions[name] = dict(type='object', properties=properties, additionalProperties=False)
        return {'$ref': '#/$defs/' + name}

    def scalar(field):
        if field.type == F.TYPE_MESSAGE:
            return message(field.message_type)
        if field.type == F.TYPE_ENUM:
            return {'type': 'string', 'enum': [value.name for value in field.enum_type.values]}
        if field.type == F.TYPE_STRING:
            return {'type': 'string'}
        if field.type == F.TYPE_BYTES:
            return {'type': 'string', 'contentEncoding': 'base64'}
        if field.type == F.TYPE_BOOL:
            return {'type': 'boolean'}
        if field.type in {F.TYPE_INT64, F.TYPE_UINT64, F.TYPE_SINT64, F.TYPE_FIXED64, F.TYPE_SFIXED64}:
            return {'type': 'string', 'pattern': r'^-?[0-9]+$'}
        return {'type': 'number' if field.type in {F.TYPE_DOUBLE, F.TYPE_FLOAT} else 'integer'}

    methods = {}
    for service in pb.DESCRIPTOR.services_by_name.values():
        for method in service.methods:
            methods[service.name + '/' + method.name] = dict(
                request=message(method.input_type)['$ref'], response=message(method.output_type)['$ref'],
                serverStreaming=method.server_streaming, clientStreaming=method.client_streaming)
    return {'$schema': JSON_SCHEMA, '$defs': definitions, 'x-rpcMethods': methods}


